import { useState } from 'react';
import { Check, Copy, FileText, Printer, RefreshCw, Sparkles } from 'lucide-react';
import { api, type Brief as BriefT, type Dataset } from '../api';
import { useApp } from '../context';
import { DatasetGate } from '../components/Gate';
import { ErrorNote, Markdown, Skeleton, Spinner } from '../components/ui';
import { fmtChange, fmtKpi, isNum } from '../format';

const cache: Record<string, BriefT> = {};

function toMarkdown(b: BriefT, ds: Dataset): string {
  const lines: string[] = [];
  lines.push(`# ${b.title}`, '');
  lines.push(`_Dataset: ${ds.name} · Generated ${new Date(b.generated_at).toLocaleString()}_`, '');
  if (b.kpis.length) {
    lines.push('| KPI | Value | Change | Period |', '|---|---:|---:|---|');
    for (const k of b.kpis) lines.push(`| ${k.label} | ${fmtKpi(k.value, k.format)} | ${isNum(k.change_pct) ? fmtChange(k.change_pct) : '—'} | ${k.period} |`);
    lines.push('');
  }
  lines.push('## Summary', '', b.summary.trim(), '');
  for (const s of b.sections) lines.push(`## ${s.heading}`, '', s.body.trim(), '');
  lines.push('---', '_Generated by DataRat — AI decision intelligence (github.com/salimkt)_');
  return lines.join('\n');
}

function fmtGenerated(s: string) {
  const d = new Date(s);
  return Number.isNaN(d.getTime()) ? s : d.toLocaleString('en-US', { dateStyle: 'long', timeStyle: 'short' });
}

function BriefPage({ ds }: { ds: Dataset }) {
  const { toast, health } = useApp();
  const [brief, setBrief] = useState<BriefT | null>(() => cache[ds.id] ?? null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [copied, setCopied] = useState(false);
  const [forId, setForId] = useState(ds.id);
  if (forId !== ds.id) {
    setForId(ds.id);
    setBrief(cache[ds.id] ?? null);
    setError(null);
  }

  const generate = async () => {
    setBusy(true);
    setError(null);
    try {
      const b = await api.brief(ds.id);
      cache[ds.id] = b;
      setBrief(b);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  };

  const copy = async () => {
    if (!brief) return;
    try {
      await navigator.clipboard.writeText(toMarkdown(brief, ds));
      setCopied(true);
      toast('Brief copied as Markdown', 'success');
      window.setTimeout(() => setCopied(false), 1800);
    } catch {
      toast('Clipboard is not available in this browser', 'error');
    }
  };

  return (
    <div className="stack">
      <div className="page-head no-print">
        <div>
          <div className="eyebrow">Board-ready summary</div>
          <h2 className="page-title">Executive Brief</h2>
          <p className="muted">
            A one-page narrative of {ds.name}: headline KPIs, what changed, risks and recommended actions
            {health ? (health.llm ? ' — written by Claude.' : ' — templated from automatic insights.') : '.'}
          </p>
        </div>
        <div className="row gap-sm wrap">
          {brief && (
            <>
              <button className="btn" onClick={() => void copy()}>
                {copied ? <Check size={16} aria-hidden="true" /> : <Copy size={16} aria-hidden="true" />} Copy Markdown
              </button>
              <button className="btn" onClick={() => window.print()}>
                <Printer size={16} aria-hidden="true" /> Print / PDF
              </button>
            </>
          )}
          {(brief || busy) && (
          <button className="btn btn-primary" onClick={() => void generate()} disabled={busy}>
            {busy ? (
              <Spinner size={16} label="Generating…" />
            ) : brief ? (
              <>
                <RefreshCw size={16} aria-hidden="true" /> Regenerate
              </>
            ) : (
              <>
                <Sparkles size={16} aria-hidden="true" /> Generate brief
              </>
            )}
          </button>
          )}
        </div>
      </div>

      {error && <ErrorNote message={error} onRetry={() => void generate()} />}

      {busy && !brief && (
        <div className="paper" aria-busy="true">
          <Skeleton h={28} w="60%" />
          <div style={{ height: 16 }} />
          <div className="grid-kpi">
            {[0, 1, 2, 3].map((i) => (
              <Skeleton key={i} h={70} />
            ))}
          </div>
          <div style={{ height: 20 }} />
          {[0, 1, 2, 3, 4].map((i) => (
            <div key={i} style={{ marginBottom: 10 }}>
              <Skeleton h={14} w={`${90 - i * 8}%`} />
            </div>
          ))}
        </div>
      )}

      {!brief && !busy && !error && (
        <div className="paper paper-empty">
          <FileText size={32} aria-hidden="true" />
          <h3>Generate an executive brief for {ds.name}</h3>
          <p className="muted">Perfect for a Monday leadership sync or a board pre-read. Print it or paste it into email, Notion or Slack.</p>
          <button className="btn btn-primary" onClick={() => void generate()}>
            <Sparkles size={16} aria-hidden="true" /> Generate brief
          </button>
        </div>
      )}

      {brief && (
        <article className={`paper brief ${busy ? 'dim' : ''}`}>
          <header className="brief-head">
            <div className="brief-brand">
              <svg width="20" height="20" viewBox="0 0 32 32" aria-hidden="true">
                <rect width="32" height="32" rx="8" fill="var(--accent)" />
                <path d="M8 22V14M13 22V9M18 22v-6M23 22V12" stroke="#fff" strokeWidth="3" strokeLinecap="round" />
              </svg>
              DataRat · Executive Brief
            </div>
            <h1>{brief.title}</h1>
            <div className="muted small">
              {ds.name} · {ds.rows.toLocaleString()} rows · Generated {fmtGenerated(brief.generated_at)}
            </div>
          </header>

          {brief.kpis.length > 0 && (
            <div className="brief-kpis">
              {brief.kpis.slice(0, 8).map((k) => (
                <div key={k.label} className="brief-kpi">
                  <div className="kpi-label">{k.label}</div>
                  <div className="brief-kpi-value">{fmtKpi(k.value, k.format)}</div>
                  <div className="muted small">
                    {isNum(k.change_pct) && <span className={k.change_pct >= 0 ? 'text-good' : 'text-bad'}>{fmtChange(k.change_pct)} </span>}
                    {k.period}
                  </div>
                </div>
              ))}
            </div>
          )}

          <section className="brief-section">
            <h2>Summary</h2>
            <Markdown>{brief.summary}</Markdown>
          </section>
          {brief.sections.map((s, i) => (
            <section key={i} className="brief-section">
              <h2>{s.heading}</h2>
              <Markdown>{s.body}</Markdown>
            </section>
          ))}
          <footer className="brief-foot muted small">Prepared with DataRat — AI decision intelligence · github.com/salimkt</footer>
        </article>
      )}
    </div>
  );
}

export default function Brief() {
  return <DatasetGate>{(ds) => <BriefPage ds={ds} />}</DatasetGate>;
}
